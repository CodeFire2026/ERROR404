# Ejercio 1: Iterar un rango de 0 a 10 e imprimir números divisibles entre 3

for i in range(11):
    if i % 3 == 0:
        print(i)
else:
    print("Estos son los números divisibles por 3.")

# Ejercicio 2: Crear un rango de numeros de 2 a 6 e impremelos

for i in range(2,7):
    print(i)
else:
    print("Ya se representó la lista.")

# Ejercicio 3: Crear un rango de 3 a 10 pero con incremento de 2 en 2, en lugar de 1 en 1
for i in range(3,11,2):
    print(i)
